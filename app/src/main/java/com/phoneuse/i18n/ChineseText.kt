    fun translate(english: String): String? {
        direct[english]?.let { return it }
        Regex("""^Error: (.*)$""").matchEntire(english)?.let { return "错误：" + it.groupValues[1] }
        Regex("""^Quick helper: (.*)$""").matchEntire(english)?.let { return "快速助手：" + it.groupValues[1] }
        Regex("""^Routine · (.*)$""").matchEntire(english)?.let { return "自动流程 · " + it.groupValues[1] }
        Regex("""^Me: (.*)$""").matchEntire(english)?.let { return "我：" + it.groupValues[1] }
        Regex("""^Start: (.*)$""").matchEntire(english)?.let { return "开始：" + it.groupValues[1] }
        Regex("""^(\d+) needed$""").matchEntire(english)?.let { return "还需授权 " + it.groupValues[1] + " 项" }
        Regex("""^(\d+) things remembered$""").matchEntire(english)?.let { return "已记住 " + it.groupValues[1] + " 项内容" }
